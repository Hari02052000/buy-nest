"use client";

import Link from "next/link";
import { usePathname } from "next/navigation";
import { cn } from "@/lib/utils";

interface AdminNavItemProps {
  href: string;
  label: string;
  icon: React.ReactNode;
  badge?: string | number;
}

export function AdminNavItem({ href, label, icon, badge }: AdminNavItemProps) {
  const pathname = usePathname();
  const isActive = pathname === href || (href !== "/admin" && pathname.startsWith(href));

  return (
    <Link
      href={href}
      className={cn(
        "flex items-center gap-3 px-4 py-3 rounded-md transition-colors duration-150",
        "focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-primary focus-visible:ring-offset-2 focus-visible:ring-offset-surface",
        isActive
          ? "bg-primary/10 text-primary font-medium"
          : "text-foreground-secondary hover:bg-surface-subtle hover:text-foreground"
      )}
      aria-current={isActive ? "page" : undefined}
    >
      <span className="flex-shrink-0" aria-hidden="true">{icon}</span>
      <span className="truncate text-sm">{label}</span>
      {badge && (
        <span
          className={cn(
            "ml-auto flex-shrink-0 px-2 py-0.5 text-xs font-medium rounded-full",
            isActive
              ? "bg-primary text-primary-foreground"
              : "bg-surface-subtle text-foreground-secondary"
          )}
        >
          {badge}
        </span>
      )}
    </Link>
  );
}

